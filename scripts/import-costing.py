"""
One-off extractor: kumbhaja_costing_1.xlsx -> src/server/db/seed-data/costing.json

Emits ONLY the raw inputs from the workbook (manufacturing cost, packing cost,
product dimensions, packed weight) plus the assumption block. Deliberately does
NOT emit the sheet's computed prices: those are Zone-A/NCR-only figures, and
prices are recomputed from src/server/pricing so a change to any rate or margin
propagates coherently to every SKU.

Uses the standard library only - .xlsx is a zip of XML.

    python scripts/import-costing.py
"""

from __future__ import annotations

import json
import re
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

NS = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
RNS = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "kumbhaja_costing_1.xlsx"
DEST = ROOT / "src" / "server" / "db" / "seed-data" / "costing.json"


def read_sheets(path: Path) -> dict[str, dict[str, str]]:
    """Return {sheet_name: {cell_ref: value}} with shared strings resolved."""
    with zipfile.ZipFile(path) as z:
        shared: list[str] = []
        if "xl/sharedStrings.xml" in z.namelist():
            for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall(f"{NS}si"):
                shared.append("".join(t.text or "" for t in si.iter(f"{NS}t")))

        rels = {
            r.get("Id"): r.get("Target")
            for r in ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
        }
        workbook = ET.fromstring(z.read("xl/workbook.xml"))

        sheets: dict[str, dict[str, str]] = {}
        for node in workbook.iter(f"{NS}sheet"):
            target = rels[node.get(f"{RNS}id")].lstrip("/").replace("xl/", "")
            cells: dict[str, str] = {}
            for c in ET.fromstring(z.read(f"xl/{target}")).iter(f"{NS}c"):
                ref, ctype = c.get("r"), c.get("t")
                v = c.find(f"{NS}v")
                if ctype == "s" and v is not None:
                    cells[ref] = shared[int(v.text)]
                elif ctype == "inlineStr":
                    node_is = c.find(f"{NS}is")
                    cells[ref] = (
                        "".join(t.text or "" for t in node_is.iter(f"{NS}t"))
                        if node_is is not None
                        else ""
                    )
                elif v is not None and v.text is not None:
                    cells[ref] = v.text
            sheets[node.get("name")] = cells
        return sheets


def num(cells: dict[str, str], ref: str) -> float | None:
    raw = cells.get(ref)
    if raw is None or raw == "":
        return None
    try:
        return float(raw)
    except ValueError:
        return None


def as_int(value: float | None) -> int | None:
    return None if value is None else int(round(value))


def main() -> None:
    if not SOURCE.exists():
        raise SystemExit(f"Source workbook not found: {SOURCE}")

    sheets = read_sheets(SOURCE)
    assumptions = sheets["Assumptions"]
    costing = sheets["Costing"]

    # Data rows start at 5 and stop at the first row without a product name.
    products = []
    row = 5
    while True:
        name = costing.get(f"B{row}")
        if not name or not costing.get(f"D{row}"):
            break

        length_cm, width_cm, height_cm = (
            num(costing, f"F{row}"),
            num(costing, f"G{row}"),
            num(costing, f"H{row}"),
        )
        products.append(
            {
                "sourceRow": row,
                "index": as_int(num(costing, f"A{row}")),
                "name": name.strip(),
                "sizeLabel": (costing.get(f"C{row}") or "").strip(),
                "mfgCostInr": num(costing, f"D{row}"),
                "packingCostInr": num(costing, f"E{row}"),
                # Millimetres so every stored dimension is an exact integer.
                "productLengthMm": as_int(length_cm * 10 if length_cm else None),
                "productWidthMm": as_int(width_cm * 10 if width_cm else None),
                "productHeightMm": as_int(height_cm * 10 if height_cm else None),
                "packedWeightGrams": as_int((num(costing, f"M{row}") or 0) * 1000) or None,
                # The workbook states these are estimates, not measurements.
                "measurementsVerified": False,
                # Kept only to verify our formula reproduces the sheet at Zone A.
                "_sheetZoneAShippingInr": as_int(num(costing, f"O{row}")),
                "_sheetSalePriceInr": as_int(num(costing, f"T{row}")),
            }
        )
        row += 1

    payload = {
        "_comment": (
            "GENERATED by scripts/import-costing.py from kumbhaja_costing_1.xlsx. "
            "Raw inputs only. Fields prefixed with _ are the workbook's own NCR-only "
            "figures, retained purely as a regression check on our formula. "
            "Do not edit by hand - re-run the script."
        ),
        "sourceFile": SOURCE.name,
        "assumptions": {
            "volumetricDivisor": as_int(num(assumptions, "B5")),
            "firstSlabInr": num(assumptions, "B6"),
            "additionalSlabInr": num(assumptions, "B7"),
            "shippingGstRate": num(assumptions, "B8"),
            "packingPaddingPerSideCm": num(assumptions, "B9"),
            "marginRate": num(assumptions, "B12"),
            "breakageRate": num(assumptions, "B13"),
        },
        "products": products,
    }

    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(products)} products -> {DEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
